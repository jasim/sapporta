#!/usr/bin/env zx

import { mkdtemp, readFile, writeFile } from "node:fs/promises";
import { realpathSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { $, fs } from "zx";

const scriptArgIndex = process.argv.findIndex(
  (arg) =>
    arg.endsWith("scripts/generate-project-auth-schema.mjs") ||
    arg.endsWith("scripts/generate-project-auth-schema.mts") ||
    arg.endsWith("generate-project-auth-schema.mjs") ||
    arg.endsWith("generate-project-auth-schema.mts"),
);
const outputArg =
  scriptArgIndex >= 0 ? process.argv[scriptArgIndex + 1] : process.argv[2];
const outputPath = resolve(
  outputArg ?? "packages/core/src/templates/project-auth/schema.ts",
);
const sharedOptionsPath = resolve(
  "packages/core/src/templates/project-auth/options.ts",
);
const scaffoldSpecsJson = (
  await $`pnpm exec tsx --eval ${`
    import { resolveScaffoldPackages } from "./packages/core/src/cli/init-project/create-project.ts";
    import { initProjectPackagePaths } from "./packages/core/src/cli/init-project/paths.ts";

    const packages = resolveScaffoldPackages(
      initProjectPackagePaths(),
      process.env.SAPPORTA_PACKAGE_ROOT ?? process.cwd(),
    );
    console.log(JSON.stringify({
      betterAuth: packages.specs.betterAuth,
      betterAuthCli: packages.specs.betterAuthCli,
    }));
  `}`
).stdout.trim();
const scaffoldSpecs = JSON.parse(scaffoldSpecsJson);

const command = "pnpm zx scripts/generate-project-auth-schema.mjs";
const betterAuthRuntimeSpec = scaffoldSpecs.betterAuth;
const authCliSpec = scaffoldSpecs.betterAuthCli;
const header = `// Generated by Better Auth for Sapporta's project-auth template.
// Do not edit this file directly; regenerate it with:
//   ${command}
// Source auth setup: packages/core/src/templates/project-auth/options.ts
// Runtime package spec: better-auth@${betterAuthRuntimeSpec}
// Generator package spec: auth@${authCliSpec}

`;

const authBin = (
  await $`npx -p auth@${authCliSpec} sh -lc 'command -v auth'`
).stdout.trim();

const authDist = dirname(realpathSync(authBin));
const nodeModules = dirname(dirname(authDist));
const tempDir = await mkdtemp(join(tmpdir(), "sapporta-auth-schema-"));
const configPath = join(tempDir, "auth-config.mjs");
const generatedPath = join(tempDir, "schema.ts");
const sharedOptionsUrl = pathToFileURL(sharedOptionsPath).href;

await writeFile(
  configPath,
  `import {
  createProjectAuthEmailAndPasswordOptions,
  createProjectAuthPlugins,
  projectAuthDrizzleAdapterConfig,
} from ${JSON.stringify(sharedOptionsUrl)};

const unusedAdapterMethod = async () => {
  throw new Error("The Better Auth schema generator should not call adapter methods.");
};

export default {
  options: {
    database: () => ({
      id: "drizzle",
      create: unusedAdapterMethod,
      findOne: unusedAdapterMethod,
      findMany: unusedAdapterMethod,
      count: unusedAdapterMethod,
      update: unusedAdapterMethod,
      updateMany: unusedAdapterMethod,
      delete: unusedAdapterMethod,
      deleteMany: unusedAdapterMethod,
      consumeOne: unusedAdapterMethod,
      transaction: unusedAdapterMethod,
      options: {
        ...projectAuthDrizzleAdapterConfig,
        adapterConfig: { adapterId: "drizzle" },
      },
    }),
    emailAndPassword: createProjectAuthEmailAndPasswordOptions(false),
    plugins: createProjectAuthPlugins(),
  },
};
`,
);

await $`npx -p auth@${authCliSpec} auth generate --config ${configPath} --output ${generatedPath} --yes`;

const generatedCode = await readFile(generatedPath, "utf8");
await fs.ensureDir(dirname(outputPath));
await writeFile(outputPath, `${header}${generatedCode}`);
console.log(`Wrote Better Auth schema to ${outputPath}`);
